#!/usr/bin/env python3
# Makes bsp/<board>/pins.h from the pin map spreadsheet (PinMap sheet).
# Usage: gen_pins.py <workbook.xlsx> <out pins.h>
# Rows with a net name are assigned. C name = net name (the schematic is the source of truth,
# the fw label column isn't used).
# Fails if a pin or name is used twice.
import re
import sys
from pathlib import Path

import openpyxl

# Fixes to the sheet (2026-10-14). Once the sheet is fixed the script errors
# so these get deleted.
OVERRIDES = {
	# LEDs: sheet has PA9 i/o type blank and PA10 as input
	"PA9": {"i/o type": "o"},
	"PA10": {"i/o type": "o"},
	# PHY reset (ENET_RST_L): sheet has i/o type blank. Output, starts low = PHY held in reset
	"PC0": {"i/o type": "o"},
	# Sheet has no AF for USB. AF10 = GPIO_AF10_OTG1_HS (stm32h7xx_hal_gpio_ex.h, parts without USB2_OTG_FS)
	"PA11": {"AF": "AF10"},
	"PA12": {"AF": "AF10"},
}

# Left at reset for now
SKIP_MODULES = {"System"}

# Backup domain pins, keep them slow. TODO DS13313 ref
LOW_SPEED_PINS = {"PC13", "PC14", "PC15"}

REQUIRED = ["port pin", "net name", "module", "function", "AF", "pin", "i/o type"]


def Die(msg):
	sys.exit(f"gen_pins: error: {msg}")


def LoadRows(path):
	wb = openpyxl.load_workbook(path, data_only=True)
	if "PinMap" not in wb.sheetnames:
		Die("no PinMap sheet")
	ws = wb["PinMap"]
	hdr = [c.value for c in ws[1]]
	for h in REQUIRED:
		if h not in hdr:
			Die(f"missing column '{h}'")
	rows = []
	for r in ws.iter_rows(min_row=2, values_only=True):
		d = dict(zip(hdr, r))
		if d["net name"] not in (None, ""):
			rows.append(d)
	return rows


def ApplyOverrides(rows):
	by_pin = {r["port pin"]: r for r in rows}
	for pp, ov in OVERRIDES.items():
		if pp not in by_pin:
			Die(f"override for {pp} but pin is unassigned in sheet")
		r = by_pin[pp]
		if all(r.get(k) == v for k, v in ov.items()):
			Die(f"override for {pp} is now redundant; delete it from OVERRIDES")
		r.update(ov)


def Classify(r):
	module = r["module"]
	io = (r["i/o type"] or "").strip()
	func = r["function"] or ""
	if module in SKIP_MODULES:
		return None
	if module == "Analog":
		return "PIN_MODE_ANALOG"
	if module == "GPIO":
		return "PIN_MODE_OUT" if io == "o" else "PIN_MODE_IN"
	if module == "Timer":
		# PWM outputs held low as GPIO until there's a PWM driver, so valves never float
		return "PIN_MODE_PARK_LOW"
	if r["AF"] in (None, ""):
		Die(f"{r['port pin']}: module {module} ({func}) has no AF")
	return "PIN_MODE_AF"


def Main():
	if len(sys.argv) != 3:
		Die("usage: gen_pins.py <workbook.xlsx> <out pins.h>")
	src = Path(sys.argv[1])
	out = Path(sys.argv[2])
	rows = LoadRows(src)
	ApplyOverrides(rows)

	seen_pin = {}
	seen_id = {}
	entries = []
	skipped = []
	for r in sorted(rows, key=lambda r: (r["port pin"][1], int(re.match(r"P[A-Z](\d+)", r["port pin"]).group(1)))):
		pp = r["port pin"]
		m = re.fullmatch(r"P([A-K])(\d+)(_C)?", pp)
		if not m:
			Die(f"bad port pin '{pp}'")
		port, num = m.group(1), int(m.group(2))
		label = r["net name"]
		ident = re.sub(r"[^A-Z0-9_]", "_", str(label).strip().upper())
		if pp in seen_pin:
			Die(f"{pp} assigned twice ({seen_pin[pp]}, {ident})")
		if ident in seen_id:
			Die(f"identifier {ident} used twice ({seen_id[ident]}, {pp})")
		seen_pin[pp] = ident
		seen_id[ident] = pp

		mode = Classify(r)
		if mode is None:
			skipped.append((ident, pp, r["module"]))
			continue
		# PARK_LOW pins keep their sheet AF so their driver can switch them over later
		af = int(str(r["AF"]).replace("AF", "")) if mode in ("PIN_MODE_AF", "PIN_MODE_PARK_LOW") else 0
		otype = "PIN_OT_OD" if "I2C" in (r["function"] or "") else "PIN_OT_PP"
		if pp in LOW_SPEED_PINS:
			speed = "PIN_SPEED_LOW"
		elif r["module"] in ("Ethernet", "USB"):
			speed = "PIN_SPEED_VHIGH"
		else:
			speed = "PIN_SPEED_MED"
		entries.append((ident, port, num, mode, af, otype, speed, pp, r["function"] or "", r["net name"]))

	w = max(len(e[0]) for e in entries)
	lines = []
	lines.append("// Generated by tools/gen_pins.py, don't edit")
	lines.append(f"// From {src.name}, PinMap sheet")
	if OVERRIDES:
		lines.append("// Overrides: " + ", ".join(sorted(OVERRIDES)) + " (see gen_pins.py)")
	lines.append("#ifndef _PINS_H_")
	lines.append("#define _PINS_H_")
	lines.append("")
	lines.append('#include "pin_types.h"')
	lines.append("")
	for e in entries:
		ident, port, num, mode, af, *_rest = e
		pp, func, net = e[7], e[8], e[9]
		lines.append(f"// {pp:6} {net} [{func}]")
		lines.append(f"#define PIN_{ident}_PORT{'':{w - len(ident)}} GPIO{port}")
		lines.append(f"#define PIN_{ident}_PORT_IDX{'':{w - len(ident)}} {ord(port) - ord('A')}u")
		lines.append(f"#define PIN_{ident}_NUM{'':{w - len(ident)}}  {num}u")
		lines.append(f"#define PIN_{ident}_MASK{'':{w - len(ident)}} (1u << {num})")
		if mode in ("PIN_MODE_AF", "PIN_MODE_PARK_LOW"):
			lines.append(f"#define PIN_{ident}_AF{'':{w - len(ident)}}   {af}u")
		tm = re.fullmatch(r"TIM(\d+)_CH(\d)", func)
		if tm:
			# timer output: which timer / channel, so drivers don't hardcode it
			lines.append(f"#define PIN_{ident}_TIM{'':{w - len(ident)}}  TIM{tm.group(1)}")
			lines.append(f"#define PIN_{ident}_TIMCH{'':{w - len(ident)}} {tm.group(2)}u")
	lines.append("")
	lines.append("// X(id, port letter, pin, mode, af, otype, speed)")
	lines.append("#define PINS_TABLE(X) \\")
	for ident, port, num, mode, af, otype, speed, *_ in entries:
		lines.append(f"\tX({ident + ',':{w + 1}} {port}, {num:2}, {mode + ',':18} {af:2}, {otype}, {speed}) \\")
	lines.append("")
	lines.append("// In the sheet but not set up here:")
	for ident, pp, mod in skipped:
		lines.append(f"//   {pp:6} {ident} ({mod})")
	lines.append("")
	lines.append("#endif")
	out.write_text("\n".join(lines) + "\n", newline="\n")
	print(f"gen_pins: {len(entries)} pins configured, {len(skipped)} skipped -> {out}")


if __name__ == "__main__":
	Main()
